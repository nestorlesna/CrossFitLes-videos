def load(slug):
    s = json.load(open(os.path.join(R, "ejercicios", slug + ".json"), encoding="utf-8"))
    return s, Stage(s["rig"]), {k: fk(v) for k, v in s["poses"].items()}


def seqloop(a, b, ta=1.0, tb=1.5, at=0.5): return {"seq": [[a, ta], [b, tb]], "at": at, "until": "end"}
C = lambda p: {"cut": p, "at": 0}
TO = lambda p, at=0.6, dur=1.0: {"to": p, "at": at, "dur": dur}


def cable_prop(s):
    return next(p for p in s["props"] if p["type"] in ("cable", "cablerow", "cablecrossover"))


def build(slug, c):
    s, S, J = load(slug)
    pr = cable_prop(s)
    PU = S(*pr["pulley"])
    STX = pr["x"] - 20 if pr["type"] == "cablecrossover" else pr["x"]
    ST = S(STX, -330)
    KNOB = S(pr["pulley"][0] + 30, pr["pulley"][1])
    top, mid, bot = c["poses"]
    W_TOP = S(*J[top]["W"]); W_BOT = S(*J[bot]["W"])
    HEAD = S(*J[top]["N"])
    ELB = S(*J[bot]["E"])
    err = c["errors"]
    P = lambda k: S(*J[err[k][3]]["W"])
    return [
        hook(c["zone"], c["hook"], c["sub"], c["hook_vo"],
             [C(top), seqloop(top, bot, 1.2, 1.4, 0.4)]),
        step("LA MÁQUINA", ["POLEA", "Y PILA"], c["machine_tag"], c["machine_vo"],
             [C(top)], [ring(PU, 62, 0.8), lab((60, 800), "POLEA", "start", 0.8),
                        ring(ST, 70, 1.8), lab((60, 880), "PILA DE PESO", "start", 1.8)], 7.2),
        step("AJUSTE 1 / 2", c["a1_badge"], c["a1_tag"], c["a1_vo"],
             [C(top)], [ring(KNOB, 50, 0.8), lab((60, 800), c["a1_lab"], "start", 1.0)], 7.2),
        step("AJUSTE 2 / 2", c["a2_badge"], c["a2_tag"], c["a2_vo"],
             [C(top)], [ring(ST, 62, 0.8), lab((60, 800), c["a2_lab"], "start", 1.0)], 7.2),
        step("POSICIÓN INICIAL", c["i_badge"], c["i_tag"], c["i_vo"],
             [C(bot)], [ring(HEAD, 54, 0.8), lab((60, 800), c["i_lab"], "start", 1.0)], 7.2),
        step("PASO 1 / 3", c["s1_badge"], c["s1_tag"], c["s1_vo"],
             [C(bot), TO(top, 0.4, 1.2)], [ring(W_TOP, 54, 0.8), lab((60, 800), c["s1_lab"], "start", 1.0)], 7.4),
        step("PASO 2 / 3", c["s2_badge"], c["s2_tag"], c["s2_vo"],
             [C(top), TO(top, 0.2, 0.5)], [ring(ELB, 52, 0.8), lab((60, 800), c["s2_lab"], "start", 1.0)], 7.2),
        step("PASO 3 / 3", c["s3_badge"], c["s3_tag"], c["s3_vo"],
             [C(top), TO(bot, 0.4, 1.1)], [ring(W_BOT, 56, 0.8), lab((60, 800), c["s3_lab"], "start", 1.0)], 7.2),
        step("RESPIRACIÓN", ["RESPIRÁ"], c["br_tag"], c["br_vo"],
             [C(bot), seqloop(bot, top, 1.2, 1.2, 0.3)], mn=6.0),
        step("ASÍ NO · 1 / 3", err[0][0], err[0][1], err[0][2],
             [C(bot), TO(err[0][3], 0.5, 0.9)], [NO(1.4, (940, 660)), ring(P(0), 52, 1.4)], 7.2),
        step("ASÍ NO · 2 / 3", err[1][0], err[1][1], err[1][2],
             [C(bot), TO(err[1][3], 0.5, 0.9)], [NO(1.4, (940, 660)), ring(P(1), 54, 1.4)], 7.2),
        step("ASÍ NO · 3 / 3", err[2][0], err[2][1], err[2][2],
             [C(bot), TO(err[2][3], 0.5, 0.9)], [NO(1.4, (940, 660)), ring(P(2), 54, 1.4)], 7.2),
        keys("TIPS DEL PROFE", ["TIPS"], c["tips"], c["tips_vo"],
             [C(bot), seqloop(bot, top, 1.2, 1.2, 0.3)]),
        keys("CLAVES", ["TÉCNICA"], c["keys"], c["keys_vo"],
             [{"cut": top, "at": 0.1}]),
        reps([c["reps"]], c["reps_sub"], c["reps_vo"], c["reps_chips"],
             [C(top), seqloop(top, bot, 1.2, 1.2, 0.3)]),
        step("AL TERMINAR", c["fin_badge"], c["fin_tag"], c["fin_vo"],
             [C(top), TO(mid, 0.8, 1.4)],
             [lab((60, 800), "SIN APURO", "start", 1.0)], 6.5),
    ]


