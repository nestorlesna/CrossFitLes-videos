def load(slug):
    s = json.load(open(os.path.join(R, "ejercicios", slug + ".json"), encoding="utf-8"))
    return s, Stage(s["rig"]), {k: fk(v) for k, v in s["poses"].items()}


def seqloop(a, b, ta=1.0, tb=1.5, at=0.5): return {"seq": [[a, ta], [b, tb]], "at": at, "until": "end"}
C = lambda p: {"cut": p, "at": 0}
TO = lambda p, at=0.6, dur=1.0: {"to": p, "at": at, "dur": dur}


def build(slug, c, top, mid, bot):
    s, S, J = load(slug)
    SX = c["sx"]
    BEAM = S(SX + 110, -1030); PAR = S(SX + 130, -700); STOP = S(SX + 130, -300)
    BENCH = S(c["bx"], c["by"])
    W_TOP = S(*J[top]["W"]); W_BOT = S(*J[bot]["W"]); W_MID = S(*J[mid]["W"])
    HEAD = S(*J["TOP"]["N"]) if "TOP" in J else S(*J[top]["N"])
    ELB = S(*J["BOTTOM"]["E"]) if "BOTTOM" in J else S(*J[bot]["E"])
    err = c["errors"]
    P = lambda k: S(*J[err[k][3]]["W"])
    return [
        hook(c["zone"], c["hook"], c["sub"], c["hook_vo"],
             [C(top), seqloop(top, bot, 1.2, 1.4, 0.4)]),
        step("LA MÁQUINA", ["BARRA Y", "BANCO"], c["machine_tag"], c["machine_vo"],
             [C(top)], [ring(BEAM, 64, 0.8), lab((60, 800), "BARRA GUIADA", "start", 0.8),
                        ring(PAR, 56, 1.8), lab((60, 880), "PARANTES", "start", 1.8),
                        ring(STOP, 48, 2.8), lab((60, 960), "TOPES", "start", 2.8)], 7.2),
        step("AJUSTE 1 / 2", c["a1_badge"], c["a1_tag"], c["a1_vo"],
             [C(top)], [ring(BENCH, 60, 0.8), lab((60, 800), c["a1_lab"], "start", 1.0)], 7.2),
        step("AJUSTE 2 / 2", c["a2_badge"], c["a2_tag"], c["a2_vo"],
             [C(top)], [ring(W_TOP, 58, 0.8), lab((60, 800), c["a2_lab"], "start", 0.8)], 7.2),
        step("POSICIÓN INICIAL", c["i_badge"], c["i_tag"], c["i_vo"],
             [C(top)], [ring(HEAD, 54, 0.8), lab((60, 800), c["i_lab"], "start", 1.0)], 7.2),
        step("PASO 1 / 3", c["s1_badge"], c["s1_tag"], c["s1_vo"],
             [C(top), TO(bot, 0.4, 1.2)], [ring(W_BOT, 54, 0.8), lab((60, 800), c["s1_lab"], "start", 1.0)], 7.4),
        step("PASO 2 / 3", c["s2_badge"], c["s2_tag"], c["s2_vo"],
             [C(bot), TO(bot, 0.2, 0.5)], [ring(ELB, 52, 0.8), lab((60, 800), c["s2_lab"], "start", 1.0)], 7.2),
        step("PASO 3 / 3", c["s3_badge"], c["s3_tag"], c["s3_vo"],
             [C(bot), TO(top, 0.4, 1.1)], [ring(W_TOP, 56, 0.8), lab((60, 800), c["s3_lab"], "start", 1.0)], 7.2),
        step("RESPIRACIÓN", ["RESPIRÁ"], c["br_tag"], c["br_vo"],
             [C(top), seqloop(top, mid, 1.2, 1.2, 0.3)], mn=6.0),
        step("ASÍ NO · 1 / 3", err[0][0], err[0][1], err[0][2],
             [C(top), TO(err[0][3], 0.5, 0.9)], [NO(1.4, (940, 660)), ring(P(0), 52, 1.4)], 7.2),
        step("ASÍ NO · 2 / 3", err[1][0], err[1][1], err[1][2],
             [C(top), TO(err[1][3], 0.5, 0.9)], [NO(1.4, (940, 660)), ring(P(1), 54, 1.4) if err[1][3] in J else NO(1.4, (940, 660))], 7.2),
        step("ASÍ NO · 3 / 3", err[2][0], err[2][1], err[2][2],
             [C(top), TO(err[2][3], 0.5, 0.9)], [NO(1.4, (940, 660)), ring(P(2), 54, 1.4)], 7.2),
        keys("TIPS DEL PROFE", ["TIPS"], c["tips"], c["tips_vo"],
             [C(top), seqloop(top, bot, 1.2, 1.2, 0.3)]),
        keys("CLAVES", ["TÉCNICA"], c["keys"], c["keys_vo"],
             [{"cut": bot, "at": 0.1}]),
        reps([c["reps"]], c["reps_sub"], c["reps_vo"], c["reps_chips"],
             [C(top), seqloop(top, bot, 1.2, 1.2, 0.3)]),
        step("AL TERMINAR", c["fin_badge"], c["fin_tag"], c["fin_vo"],
             [C(bot), TO(mid, 0.8, 1.4)],
             [lab((60, 800), "SIN APURO", "start", 1.0)], 6.5),
    ]


