def common_parts(S, pr, J, start, end, extra_knob=None):
    seat = S(-240, pr["seat"][2] + 90) if "back" not in pr else S(pr["back"][0] - 10, pr["seat"][2] + 61)
    return dict(PINP=S(*PIN(pr["stack"], pr["pin"])), SEATK=seat, PV=S(*pr["pivot"]))


